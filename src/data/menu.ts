export function getCategory(id: CategoryId): Category {
  const category = categories.find((c) => c.id === id);
  if (!category) throw new Error(`Unknown category: ${id}`);
  return category;
}

export function getItemsByCategory(id: CategoryId): MenuItem[] {
  return menuItems.filter((item) => item.category === id);
}

export function getItem(slug: string): MenuItem | undefined {
  return menuItems.find((candidate) => candidate.slug === slug);
}

export function getFeatured(): MenuItem[] {
  return featuredOrder.map((slug) => {
    const item = getItem(slug);
    if (!item) throw new Error(`Featured item missing: ${slug}`);
    return item;
  });
}

export function getLead(id: CategoryId): MenuItem {
  const item = getItem(getCategory(id).leadSlug);
  if (!item) throw new Error(`Lead item missing for ${id}`);
  return item;
}
